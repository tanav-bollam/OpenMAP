"""Test the hypotheses behind the error analysis in reports/results.md.

    python src/error_analysis.py

Descriptive post-hoc analysis of existing predictions (it reads test-set predictions to explain errors;
nothing is tuned on them). Writes reports/error_analysis_tests.md.

H1  Data scarcity: genres with fewer training tracks get lower test F1.
H2  Label ambiguity: errors often predict another top-level genre the track itself carries as a tag.
H3  Acoustic overlap: in MERT embedding space, test tracks of the rare genres sit among other genres
    (nearest-neighbour label purity vs the class prior).
H4  Pairwise separability: the confused pairs are harder to separate linearly than control pairs.
H5  Intrinsic ambiguity: the CNN and MERT make the same wrong prediction on the same tracks more often
    than chance.
"""
from __future__ import annotations

import ast
import json

import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.preprocessing import StandardScaler

from utils import DATA, OUTPUTS, RAW, REPORTS, load_genres, load_splits

SUBSET = "medium"
TAGS_CACHE = DATA / "track_tags.csv"
RNG = np.random.default_rng(0)
LAYER = 6   # MERT layer with the largest learned weight


def f1_vector(y, pred, n):
    cm = np.bincount(y * n + pred, minlength=n * n).reshape(n, n)
    tp = np.diag(cm).astype(float)
    denom = cm.sum(0) + cm.sum(1)
    return np.where(denom > 0, 2 * tp / np.maximum(denom, 1), 0.0)


def load_tags(genres: list[str]) -> dict[int, set[str]]:
    """track_id -> set of top-level genre names the track is tagged with (parents included)."""
    if not TAGS_CACHE.exists():
        meta = RAW / "fma_metadata"
        g = pd.read_csv(meta / "genres.csv", index_col=0)
        top_title = {int(i): g.loc[int(t), "title"] for i, t in g["top_level"].items() if int(t) in g.index}
        tracks = pd.read_csv(meta / "tracks.csv", index_col=0, header=[0, 1])
        col = tracks[("track", "genres_all")]
        rows = {}
        for tid, val in col.items():
            try:
                ids = ast.literal_eval(val) if isinstance(val, str) else []
            except (ValueError, SyntaxError):
                ids = []
            rows[int(tid)] = "|".join(sorted({top_title[i] for i in ids if i in top_title}))
        pd.Series(rows, name="tags").rename_axis("track_id").to_csv(TAGS_CACHE)
    s = pd.read_csv(TAGS_CACHE, index_col=0)["tags"].fillna("")
    return {int(t): {x for x in v.split("|") if x in genres} for t, v in s.items()}


def load_run_probs(dirs, split="test"):
    out, ref_ids, ref_y = [], None, None
    for d in dirs:
        z = np.load(d / f"probs_{split}.npz")
        if ref_ids is None:
            ref_ids, ref_y = z["track_id"], z["labels"]
        assert (z["track_id"] == ref_ids).all()
        out.append(z["probs"])
    return np.stack(out), ref_ids, ref_y


def main() -> None:
    genres = load_genres(SUBSET)
    n = len(genres)
    df = load_splits(SUBSET)
    train = df[df.split == "training"]
    counts = np.bincount(train.label, minlength=n)

    mert_dirs = [OUTPUTS / "sweep" / f"base_s{s}" for s in range(1, 6) if (OUTPUTS / "sweep" / f"base_s{s}" / "probs_test.npz").exists()]
    cnn_dirs = [OUTPUTS / "cnn"] + [d for d in sorted(OUTPUTS.glob("cnn_s[0-9]*")) if (d / "probs_test.npz").exists()]
    mert_p, ids, y = load_run_probs(mert_dirs)
    cnn_p, ids2, y2 = load_run_probs(cnn_dirs)
    assert (ids == ids2).all() and (y == y2).all()
    models = {"MERT": mert_p, "CNN": cnn_p}
    ens_pred = {k: v.mean(0).argmax(1) for k, v in models.items()}   # seed-ensemble prediction
    tags = load_tags(genres)

    L = ["# Tests of the error-analysis explanations", "",
         "Generated by `src/error_analysis.py` from saved test predictions. This is descriptive: it explains the "
         "errors and tunes nothing. 'Supported' / 'not supported' only refer to the stated test criterion.", "",
         f"Models: MERT = {len(mert_dirs)} seeds (original recipe), CNN = {len(cnn_dirs)} seed(s); per-genre scores "
         "are averaged over seeds, and the seed-ensemble (mean probabilities) is used where one prediction per track is needed.", ""]

    # ---------------- H1: scarcity
    L += ["## H1. Data scarcity: fewer training tracks, lower F1", ""]
    verdicts = {}
    for name, p in models.items():
        f1 = np.mean([f1_vector(y, pp.argmax(1), n) for pp in p], axis=0)
        rho, pval = spearmanr(np.log(counts), f1)
        verdicts[name] = (rho, pval)
    L += ["| Model | Spearman rho (log train count vs test F1, 16 genres) | p |", "|---|---|---|"]
    L += [f"| {k} | {r:.2f} | {pv:.3f} |" for k, (r, pv) in verdicts.items()]
    h1 = all(r > 0.5 and pv < 0.05 for r, pv in verdicts.values())
    L += ["", f"**Verdict: {'supported' if h1 else 'not clearly supported'}** (criterion: rho > 0.5 and p < 0.05 for both models). "
          "Correlation across 16 genres is a coarse test; it cannot separate scarcity from acoustic difficulty "
          "(see H3/H4).", ""]

    # ---------------- H2: label ambiguity via multi-tag
    multi = float(np.mean([len(tags.get(int(t), set())) > 1 for t in ids]))
    L += ["## H2. Label ambiguity: errors often name another genre the track is also tagged with", ""]
    if multi < 0.01:
        L += [f"**Verdict: not testable on this dataset.** Only {multi:.1%} of the test tracks carry more than one top-level "
              "genre tag: FMA's `fma_medium` subset contains only tracks with a single top-level genre (in the full FMA "
              "metadata, about half of all tracks have several). So no misclassification can name 'another tag of the same "
              "track', and this check cannot support or refute label ambiguity. A side effect worth knowing: because of this "
              "selection, genre labels in FMA-medium are cleaner than in the full collection, so real-world ambiguity is "
              "probably underestimated. H4 and H5 below are the available evidence about overlap.", ""]
    else:
        L += ["For each misclassified test track: is the predicted genre one of the track's top-level tags other than its "
              "reference genre? Null: shuffle the predicted labels among the misclassified tracks (10,000 permutations).", "",
              "| Model | Errors | Predicted genre is also a tag | Null mean | Ratio | Permutation p |", "|---|---|---|---|---|---|"]
        h2 = {}
        for name, pred in ens_pred.items():
            err = np.where(pred != y)[0]
            tagsets = [tags.get(int(ids[i]), set()) for i in err]
            obs = float(np.mean([genres[pred[i]] in ts for i, ts in zip(err, tagsets)]))
            perm = pred[err].copy()
            null = np.empty(10_000)
            for k in range(10_000):
                RNG.shuffle(perm)
                null[k] = np.mean([genres[q] in ts for q, ts in zip(perm, tagsets)])
            pv = (np.sum(null >= obs) + 1) / (len(null) + 1)
            h2[name] = (obs, null.mean(), pv)
            L.append(f"| {name} | {len(err)} | {obs:.1%} | {null.mean():.1%} | {obs / max(null.mean(), 1e-9):.1f}x | {pv:.4f} |")
        h2ok = all(o > nm and pv < 0.01 for o, nm, pv in h2.values())
        L += ["", f"{multi:.1%} of test tracks carry more than one top-level tag. "
              f"**Verdict: {'supported' if h2ok else 'not supported'}** (criterion: observed share above the null with p < 0.01 for both models).", ""]

    # ---------------- H3: kNN in MERT embedding space
    mat = np.load(DATA / "embeddings_all.npy", mmap_mode="r")
    emb_ids = np.load(DATA / "embeddings_all_ids.npy")
    row = {int(t): i for i, t in enumerate(emb_ids)}

    def emb(sub):
        x = np.stack([mat[row[int(t)], LAYER] for t in sub.track_id]).astype(np.float32)
        return x

    test_df = df[df.split == "test"].set_index("track_id").loc[ids].reset_index()
    Xtr, Xte = emb(train), emb(test_df)
    sc = StandardScaler().fit(Xtr)
    Xtr_s, Xte_s = sc.transform(Xtr), sc.transform(Xte)
    Xtr_n = Xtr_s / np.linalg.norm(Xtr_s, axis=1, keepdims=True)
    Xte_n = Xte_s / np.linalg.norm(Xte_s, axis=1, keepdims=True)
    ytr = train.label.to_numpy()
    prior = counts / counts.sum()
    K = 10
    sims = Xte_n @ Xtr_n.T
    nn_idx = np.argpartition(-sims, K, axis=1)[:, :K]
    nn_lab = ytr[nn_idx]
    L += [f"## H3. Acoustic overlap: nearest neighbours in MERT layer-{LAYER} space", "",
          f"For test tracks of each genre, the share of their {K} nearest TRAINING tracks (cosine, standardized embeddings) "
          "that carry the same label, against the share expected if neighbours were drawn at random from the class prior. "
          "Lift = observed / expected (1.0 means no local structure).", "",
          "| Genre | Test tracks | Same-label share | Expected by prior | Lift | Most frequent neighbour genre |", "|---|---|---|---|---|---|"]
    lifts = {}
    for gname in ["Soul-RnB", "Blues", "Easy Listening", "Pop", "Instrumental", "Folk", "Classical", "Hip-Hop", "Rock"]:
        gi = genres.index(gname)
        m = y == gi
        share = (nn_lab[m] == gi).mean()
        lift = share / prior[gi]
        top = np.bincount(nn_lab[m].ravel(), minlength=n).argmax()
        lifts[gname] = lift
        L.append(f"| {gname} | {int(m.sum())} | {share:.1%} | {prior[gi]:.1%} | {lift:.1f}x | {genres[top]} |")
    L += ["", "Reading: a large lift for a rare genre means its tracks do cluster together (so low F1 would be mainly a data-quantity / "
          "decision-boundary problem); a lift near 1 means they are dispersed among other genres (acoustic or label overlap).", ""]

    # ---------------- H4: pairwise separability (linear probe AUC)
    pairs = [("Instrumental", "Folk"), ("Pop", "Electronic"), ("Soul-RnB", "Rock"), ("Folk", "Rock"),
             ("Classical", "Hip-Hop"), ("Electronic", "Classical")]
    L += ["## H4. Pairwise separability (logistic regression on MERT layer-%d embeddings)" % LAYER, "",
          "Balanced class weights, trained on the training split, ROC-AUC on the test split. The last two pairs are acoustically distant controls.", "",
          "| Pair | Train tracks (A / B) | Test tracks (A / B) | AUC |", "|---|---|---|---|"]
    aucs = {}
    for a, b in pairs:
        ai, bi = genres.index(a), genres.index(b)
        tr = np.isin(ytr, [ai, bi])
        te = np.isin(y, [ai, bi])
        clf = LogisticRegression(max_iter=2000, C=0.1, class_weight="balanced").fit(Xtr_s[tr], (ytr[tr] == ai).astype(int))
        auc = roc_auc_score((y[te] == ai).astype(int), clf.decision_function(Xte_s[te]))
        aucs[(a, b)] = auc
        L.append(f"| {a} vs {b} | {int((ytr == ai).sum())} / {int((ytr == bi).sum())} | {int((y == ai).sum())} / {int((y == bi).sum())} | {auc:.3f} |")
    ctrl = np.mean([aucs[("Classical", "Hip-Hop")], aucs[("Electronic", "Classical")]])
    conf = np.mean([aucs[p] for p in pairs[:4]])
    L += ["", f"Mean AUC of the confused pairs {conf:.3f} vs controls {ctrl:.3f}. "
          f"**Verdict: {'supported' if conf < ctrl - 0.05 else 'not supported'}** (criterion: confused pairs at least 0.05 AUC below the controls). "
          "A low AUC is consistent with real acoustic/label overlap, not only with scarcity, because the classifier is class-balanced.", ""]

    # ---------------- H5: shared errors
    cn, mn = ens_pred["CNN"], ens_pred["MERT"]
    both = (cn != y) & (mn != y)
    same_wrong = both & (cn == mn)
    exp_same = 0.0
    pm = np.bincount(mn[both], minlength=n) / max(both.sum(), 1)
    pc = np.bincount(cn[both], minlength=n) / max(both.sum(), 1)
    exp_same = float((pm * pc).sum())
    L += ["## H5. Do the two models fail on the same tracks in the same way?", "",
          f"- CNN wrong: {(cn != y).sum()}, MERT wrong: {(mn != y).sum()}, both wrong: {int(both.sum())} of {len(y)} test tracks.",
          f"- Among tracks both get wrong, they predict the SAME wrong genre {same_wrong.sum() / max(both.sum(), 1):.1%} of the time "
          f"(expected if independent given their prediction frequencies: {exp_same:.1%}).",
          f"- Share of the CNN's errors that MERT also makes: {both.sum() / max((cn != y).sum(), 1):.1%}; "
          f"share of MERT's errors that the CNN also makes: {both.sum() / max((mn != y).sum(), 1):.1%}.", "",
          f"**Verdict: {'supported' if same_wrong.sum() / max(both.sum(), 1) > 1.5 * exp_same else 'not supported'}** "
          "(criterion: shared-wrong-label rate above 1.5x the independence expectation). "
          "Shared mistakes of two very different models point to ambiguous tracks or labels rather than model-specific weaknesses.", ""]

    REPORTS.mkdir(exist_ok=True)
    out = REPORTS / "error_analysis_tests.md"
    out.write_text("\n".join(L), encoding="utf-8")
    import sys
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main()
